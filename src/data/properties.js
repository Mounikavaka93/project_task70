export const spotlightCities = ['San Francisco', 'New York', 'Los Angeles', 'Miami', 'Austin', 'Chicago']

export const locationSuggestions = [...new Set(properties.flatMap((property) => [property.city, property.location]))].sort(
  (a, b) => a.localeCompare(b),
)

export function getProperty(id) {
  return properties.find((property) => property.id === id)
}

export function getAgent(id) {
  return agents[id]
}

export function getSavedProperties(ids) {
  return ids.map((id) => getProperty(id)).filter(Boolean)
}

export function relatedProperties(property, limit = 3) {
  return properties
    .filter((item) => item.id !== property.id)
    .map((item) => ({
      item,
      score:
        (item.city === property.city ? 4 : 0) +
        (item.listing === property.listing ? 2 : 0) +
        (item.type === property.type ? 1 : 0),
    }))
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((entry) => entry.item)
}

export function citySpots() {
  return spotlightCities.map((city) => {
    const matches = properties.filter((property) => property.city === city)
    return {
      city,
      sales: matches.filter((property) => property.listing === 'sale').length,
      rents: matches.filter((property) => property.listing === 'rent').length,
      image: matches[0]?.images[0],
    }
  })
}
